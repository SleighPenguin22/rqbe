#[derive(Debug, Hash, PartialEq, Eq, Clone, Copy)]
pub struct ILABITyp {
    pub(crate) base: ILType,
    pub(crate) sign: Option<bool>,
}

impl ILABITyp {
    pub fn signed(base: ILType) -> Self {
        Self {
            base,
            sign: Some(true),
        }
    }
    pub fn unsigned(base: ILType) -> Self {
        Self {
            base,
            sign: Some(false),
        }
    }
    pub fn nonsigned(base: ILType) -> Self {
        Self { base, sign: None }
    }
}

